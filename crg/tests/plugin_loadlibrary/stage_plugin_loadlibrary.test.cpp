// STAGE plugin_loadlibrary — Manual-Load Plugin: the CppCon Acte 1 pattern
// ─────────────────────────────────────────────────────────────────────────────
// PROBLEM:
//   You want to load a plugin .dll/.so at runtime, have it inject capabilities
//   into the host routing tensor, invoke them, and cleanly unload — without any
//   managed loader, without any GridZero .cpp compiled into the host or plugin,
//   and without any code change on the host side.
//
// SOLUTION — Manual LoadLibrary + CRG_Bootstrap / CRG_Shutdown:
//   1. The HOST builds a HostDescriptor (its AnchorLink chain head) and a
//      CRG_Context pointing to it.
//   2. The HOST calls LoadLibrary / dlopen (its own code — zero GridZero .cpp).
//   3. The HOST looks up CRG_Bootstrap and calls it with the context.
//      CRG_Bootstrap (generated by CRG_DEFINE_PLUGIN in the DLL) splices the
//      plugin's local AnchorLink chain into the host anchor, then calls each
//      ISyncNode::OnPluginLoad — all via the header-only machinery in crg_core.
//   4. The HOST refreshes the routing cache (CapabilityRouter::RefreshCache)
//      so the new capabilities become visible to Find().
//   5. The HOST invokes capabilities as usual — the plugin's Execute() runs.
//   6. The HOST calls CRG_Shutdown, then dlclose/FreeLibrary.
//      CRG_Shutdown splices the plugin's chain back out; RefreshCache restores
//      the pre-load state.
//
// WHAT THIS STAGE PROVES:
//   - Zero GridZero .cpp in the host binary.
//   - Zero GridZero .cpp in the plugin binary (only headers from crg_core).
//   - The host writes one LoadLibrary + two GetProcAddress calls; that is the
//     entire integration surface.
//   - After unload, the routing tensor is identical to the pre-load state.
//
// DEPENDENCIES:
//   - crg_core (header-only)
//   - CRG_PLUGINS_ENABLED=1 (activates plugin.hpp / universal_anchor / ISyncNode)
//   - CRG_GREETER_PLUGIN_PATH injected by CMake (path to the built DLL/SO)
// ═════════════════════════════════════════════════════════════════════════════

